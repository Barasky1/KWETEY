using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.RazorPages;
using Microsoft.EntityFrameworkCore;
using KWETEY.Data;
using KWETEY.Models;

namespace KWETEY.Pages.Students
{
    public class EnrollModel : PageModel
    {
        private readonly ApplicationDbContext _context;

        public EnrollModel(ApplicationDbContext context)
        {
            _context = context;
        }

        // The Student Object being created
        [BindProperty]
        public Student Student { get; set; }

        // The ID that appears in the blue badge on the UI
        public string AutoGeneratedId { get; set; }

        // GET: Loads the page and generates the unique ID
        public async Task<IActionResult> OnGetAsync()
        {
            // 1. Get current year
            string year = DateTime.Now.Year.ToString();

            // 2. Count existing students for this school to get the next number
            // Note: We filter by the current school context from Middleware
            var schoolName = HttpContext.Items["SchoolName"] as string;

            int count = await _context.Students
                .CountAsync(s => s.AdmissionDate.Year == DateTime.Now.Year) + 1;

            // 3. Format: KW-2026-001 (D3 ensures 3 digits: 001, 002...)
            AutoGeneratedId = $"KW-{year}-{count.ToString("D3")}";

            return Page();
        }

        // POST: Saves the data and moves to the "Guardian" step
        public async Task<IActionResult> OnPostAsync()
        {
            if (!ModelState.IsValid)
            {
                // If validation fails, stay on the page but keep the ID
                await OnGetAsync();
                return Page();
            }

            // 4. Set the Admission Number from the generated value
            // We usually pass this back through a hidden input in the form

            _context.Students.Add(Student);
            await _context.SaveChangesAsync();

            // 5. Redirect to the Guardian Setup (Step 2)
            // We pass the StudentId so we know which student to attach the guardian to
            return RedirectToPage("./GuardianSetup", new { id = Student.Id });
        }
    }
}